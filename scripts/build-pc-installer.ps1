# Builds the player-facing setup program of a pc-compat game (native/pc-installer -> build/pc-installer/<name>.exe) with
# the pinned llvm-mingw. Game facts come from games/<Game>/profile.json (pcCompat + pcCompat.installer) as a generated
# header; the layer (d3d8.dll), the game's settings and the texts are embedded as resources. Nothing of the game itself
# is embedded: the setup copies the game from the player's own disc.
param(
    [string]$Game = 'PC-DPTWP-UK',
    [string]$Dll = '',
    [string]$Out = '',
    [string]$Version = '1.0.0',
    [string]$ToolsRoot = (Join-Path $env:USERPROFILE 'Tools')
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if (-not $Dll) { $Dll = Join-Path $repo 'build\pc-compat\d3d8.dll' }
if (-not $Out) { $Out = Join-Path $repo 'build\pc-installer' }
$manifest = Get-Content (Join-Path $repo 'toolchains\toolchains.json') -Raw | ConvertFrom-Json
$llvm = $manifest.tools | Where-Object { $_.id -eq 'llvm-mingw' }
$bin = Join-Path $ToolsRoot $llvm.bin
$cxx = Join-Path $bin 'i686-w64-mingw32-clang++.exe'
$windres = Join-Path $bin 'i686-w64-mingw32-windres.exe'
if (-not (Test-Path $cxx)) { throw "i686 clang++ not found at $cxx (run scripts/setup-toolchains.ps1 -Only llvm-mingw)" }
if (-not (Test-Path $Dll)) { throw "compatibility layer not built: $Dll (run scripts/build-pc-compat.ps1)" }
$env:PATH = "$bin;$env:PATH"

$gameDir = Join-Path $repo "games\$Game"
# Windows PowerShell 5.1 cannot parse // comments: drop whole-line comments before ConvertFrom-Json
$p = ((Get-Content (Join-Path $gameDir 'profile.json') -Raw) -replace '(?m)^\s*//.*$', '' | ConvertFrom-Json).pcCompat
$i = $p.installer
if (-not $i) { throw "games/$Game/profile.json has no pcCompat.installer section" }
foreach ($k in 'title', 'edition', 'folderName', 'shortcutName', 'discMarker', 'outputName', 'playerReadme') {
    if (-not $i.$k) { throw "pcCompat.installer.$k is missing" }
}
if ($p.executable.sha256 -notmatch '^[0-9a-f]{64}$') { throw 'pcCompat.executable.sha256 must be 64 lower-case hex digits' }

function Wide([string]$s) { 'L"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }  # C wide string literal
$gen = Join-Path $Out 'gen'
New-Item -ItemType Directory -Force $gen | Out-Null
$h = @(
    "// generated by scripts/build-pc-installer.ps1 from games/$Game/profile.json: do not edit",
    '#pragma once',
    "#define GAME_TITLE $(Wide $i.title)",
    "#define GAME_EDITION $(Wide $i.edition)",
    "#define GAME_EXE $(Wide $p.executable.path)",
    "#define GAME_EXE_SHA256 `"$($p.executable.sha256)`"",
    "#define GAME_PROXY $(Wide $p.proxyDll)",
    "#define DISC_MARKER $(Wide $i.discMarker)",
    "#define DEFAULT_FOLDER $(Wide $i.folderName)",
    "#define SHORTCUT_NAME $(Wide $i.shortcutName)",
    'struct InstallMap { const wchar_t* from; const wchar_t* to; };',
    'static const InstallMap kInstall[] = {'
)
foreach ($m in $p.install) { $h += "    {$(Wide $m.from), $(Wide $m.to)}," }
$h += '};'
$h += 'static const wchar_t* const kCd[] = {'
foreach ($c in $p.cd) { $h += "    $(Wide $c)," }
$h += '};'
Set-Content -Encoding Ascii (Join-Path $gen 'game_manifest.h') $h

function RcPath([string]$path) { if (-not (Test-Path $path)) { throw "missing $path" }; '"' + ((Resolve-Path $path).Path -replace '\\', '\\') + '"' }
$src = Join-Path $repo 'native\pc-installer'
$v = ($Version -split '\.') + @('0', '0', '0', '0') | Select-Object -First 4
$rc = @(
    '#include <windows.h>',
    '#include "resource.h"',
    "IDR_PROXY RCDATA $(RcPath $Dll)",
    "IDR_SETTINGS RCDATA $(RcPath (Join-Path $gameDir 'spartacompat.ini'))",
    "IDR_REGISTRY RCDATA $(RcPath (Join-Path $gameDir 'registry.ini'))",
    "IDR_LICENSE RCDATA $(RcPath (Join-Path $src 'payload\LICENSE.txt'))",
    "IDR_NOTICES RCDATA $(RcPath (Join-Path $src 'payload\THIRD_PARTY_NOTICES.txt'))",
    "IDR_README RCDATA $(RcPath (Join-Path $gameDir $i.playerReadme))",
    "1 24 $(RcPath (Join-Path $src 'app.manifest'))",
    'VS_VERSION_INFO VERSIONINFO',
    "FILEVERSION $($v -join ',')",
    "PRODUCTVERSION $($v -join ',')",
    'BEGIN',
    '  BLOCK "StringFileInfo"',
    '  BEGIN',
    '    BLOCK "040904B0"',
    '    BEGIN',
    "      VALUE `"FileDescription`", `"Setup for the unofficial PC fix of $($i.title -replace '"', '')`"",
    "      VALUE `"ProductName`", `"$($i.title -replace '"', '') PC fix (unofficial)`"",
    "      VALUE `"FileVersion`", `"$Version`"",
    "      VALUE `"ProductVersion`", `"$Version`"",
    '      VALUE "LegalCopyright", "MIT License. The game is not included."',
    "      VALUE `"OriginalFilename`", `"$($i.outputName).exe`"",
    '    END',
    '  END',
    '  BLOCK "VarFileInfo"',
    '  BEGIN',
    '    VALUE "Translation", 0x409, 1200',
    '  END',
    'END'
)
Set-Content -Encoding Ascii (Join-Path $gen 'payload.rc') $rc
$res = Join-Path $gen 'payload.res.o'
& $windres -I (Join-Path $src 'src') -O coff -o $res (Join-Path $gen 'payload.rc')
if ($LASTEXITCODE -ne 0) { throw "windres failed ($LASTEXITCODE)" }

$exe = Join-Path $Out "$($i.outputName).exe"
$argv = @('-std=c++17', '-O2', '-Wall', '-municode', '-mwindows', '-static', '-DUNICODE', '-D_UNICODE', '-D_WIN32_WINNT=0x0A00',
    '-DWINVER=0x0A00', "-I$gen", "-I$(Join-Path $src 'src')", '-o', $exe,
    (Join-Path $src 'src\main.cpp'), (Join-Path $src 'src\iso9660.cpp'), $res,
    '-lcomctl32', '-lole32', '-lshell32', '-luuid', '-lbcrypt', '-lshlwapi')
& $cxx @argv
if ($LASTEXITCODE -ne 0) { throw "build failed ($LASTEXITCODE)" }
if (-not (Test-Path $exe)) { throw "build reported success but $exe is missing" }
$hash = (Get-FileHash -Algorithm SHA256 $exe).Hash.ToLowerInvariant()
$dllHash = (Get-FileHash -Algorithm SHA256 $Dll).Hash.ToLowerInvariant()
Write-Host "built $exe"
Write-Host "  sha256 $hash"
Write-Host "  embeds d3d8.dll sha256 $dllHash"
